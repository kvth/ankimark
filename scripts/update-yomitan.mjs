#!/usr/bin/env node
// Vendors Yomitan's Japanese deinflection (the rules and the engine that applies
// them) into vendor/yomitan/, unchanged, and builds yomitan-deinflect.js from it:
// the same code as a classic script, which content scripts, the background
// script and the node tests can all load (Yomitan's files are ES modules).
//
// Usage: node scripts/update-yomitan.mjs [yomitan-release-tag]   (or: make yomitan)

import {mkdir, readFile, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const TAG = process.argv[2] ?? '26.11.2.0';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR = join(ROOT, 'vendor/yomitan');
const BUNDLE = join(ROOT, 'yomitan-deinflect.js');
// In dependency order: the rules use the helpers, nothing uses the engine.
const FILES = [
    'ext/js/language/language-transforms.js',
    'ext/js/language/ja/japanese-transforms.js',
    'ext/js/language/language-transformer.js',
];

const sources = [];
for (const file of FILES) {
    const url = `https://raw.githubusercontent.com/yomidevs/yomitan/${TAG}/${file}`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
    const text = await response.text();
    await mkdir(dirname(join(VENDOR, file)), {recursive: true});
    await writeFile(join(VENDOR, file), text);
    sources.push([file, text]);
}
await writeFile(join(VENDOR, 'VERSION'), `${TAG}\n`);

const parts = sources.map(([file, text]) => {
    const body = text
        .replace(/^import\s[\s\S]*?\sfrom\s+'[^']+';[ \t]*\n/gm, '')
        .replace(/^export (?=(const|let|class|function) )/gm, '');
    if (/^\s*(import|export)\b/m.test(body)) throw new Error(`${file}: import/export left after stripping`);
    return `// ---- ${file} ----\n\n${body.trim()}\n`;
});

await writeFile(BUNDLE, `// Generated by scripts/update-yomitan.mjs from Yomitan ${TAG}; do not edit.
// The files in vendor/yomitan/ with their import/export lines removed:
// https://github.com/yomidevs/yomitan (GPL-3.0-or-later)
(function (root) {
  "use strict";

  // language-transformer.js only uses log.warn from Yomitan's logger.
  const log = { warn: (e) => console.warn(e) };

${parts.join('\n')}
  const api = { LanguageTransformer, japaneseTransforms };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.YomitanDeinflect = api;
})(globalThis);
`);

// Make sure the bundle loads and works.
const {LanguageTransformer, japaneseTransforms} = createRequire(import.meta.url)(BUNDLE);
const transformer = new LanguageTransformer();
transformer.addDescriptor(japaneseTransforms);
if (!transformer.transform('食べなかった').some((r) => r.text === '食べる')) throw new Error('bundle check failed');
console.log(`yomitan-deinflect.js built from Yomitan ${TAG}`);
